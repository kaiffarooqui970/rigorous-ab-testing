"""Generate the bundled synthetic example experiments (committed, small, credential-free).

examples/checkout_test.csv      healthy randomized test, known true effects
examples/checkout_test_srm.csv  same design with a selective logging bug (SRM)

Both simulations use the same seed, so units, covariates and assignment are shared and
only the outcome model differs.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from xpkit.sim import ExperimentSpec, simulate_experiment

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "examples"
SEED, N = 2024, 20_000

REVENUE = ExperimentSpec(
    n=N,
    outcome="continuous",
    baseline=20.0,
    effect=0.6,
    noise_sd=6.0,
    covariate_effect=4.0,
    pre_period_noise=2.0,
)
CONVERT = ExperimentSpec(n=N, outcome="binary", baseline=0.08, effect=0.008, covariate_effect=0.8)


def build(srm: bool) -> tuple[pd.DataFrame, dict[str, float]]:
    rev = simulate_experiment(REVENUE, SEED)
    conv = simulate_experiment(CONVERT, SEED)
    assert (rev.data.treatment.to_numpy() == conv.data.treatment.to_numpy()).all()
    d = rev.data
    rng = np.random.default_rng(SEED + 1)
    df = pd.DataFrame(
        {
            "user_id": [f"u{i:06d}" for i in d.unit_id],
            "variant": np.where(d.treatment == 1, "new_checkout", "control"),
            "converted": conv.data.y.astype(int),
            "revenue": d.y.round(2),
            "pre_revenue": d.pre_metric.round(2),
            "tenure_days": np.round(np.exp(3.5 + 0.4 * d.x1 + rng.normal(0, 0.3, len(d)))).astype(
                int
            ),
            "is_mobile": (d.x2 > 0.3).astype(int),
        }
    )
    if srm:
        # Logging bug: 25% of low-engagement (x0 < 0) treated users are never recorded.
        u = np.random.default_rng(SEED + 2).random(len(d))
        lost = (d.treatment == 1) & (d.x0 < 0) & (u < 0.25)
        df = df.loc[~lost.to_numpy()].reset_index(drop=True)
    return df, {"revenue": rev.true_ate, "converted": conv.true_ate}


def main() -> None:
    OUT.mkdir(exist_ok=True)
    healthy, truth = build(srm=False)
    healthy.to_csv(OUT / "checkout_test.csv", index=False)
    broken, _ = build(srm=True)
    broken.to_csv(OUT / "checkout_test_srm.csv", index=False)
    (OUT / "README.md").write_text(
        "# Synthetic example experiments\n\n"
        "Generated by `scripts/make_examples.py` from `xpkit.sim` (seed "
        f"{SEED}). Not real data.\n\n"
        f"* `checkout_test.csv`: {len(healthy):,} users, 50/50 randomized. **True effects:** "
        f"revenue {truth['revenue']:+.3f}, conversion {truth['converted']:+.4f}.\n"
        f"* `checkout_test_srm.csv`: same design, but 25% of low-engagement treated users "
        f"were never logged (selective SRM, {len(broken):,} rows remain). The naive estimate is "
        "biased upward; the report flags the SRM and refuses to interpret it.\n\n"
        "**Caveat:** a subtler loss can slip past the SRM check. In "
        "`results/validation/stage2.json` (E_srm), a 5% selective loss at n=20k was flagged in "
        "only 59% of simulations. Passing the SRM check is necessary, not sufficient.\n\n"
        "Run `xpkit-report examples/checkout_test.csv examples/checkout_test.yaml -o "
        "reports/checkout_test.html`.\n"
    )
    print(f"truth: {truth}; rows healthy={len(healthy)} broken={len(broken)}")


if __name__ == "__main__":
    main()
